#include "frontend_text_layout.h"

#include "types.h"

#define MOVIE_STREAM_LARGE_BLOCK_SIZE 0x10000
#define MOVIE_STREAM_COMPACT_BLOCK_SIZE 0x8000
#define MOVIE_STREAM_DEFAULT_BUFFER_COUNT 10
#define MOVIE_STREAM_WIDE_BUFFER_COUNT 5

void
configure_default_movie_stream_buffers(void)
{
  G_MOVIE_STREAM_BLOCK_SIZE   = MOVIE_STREAM_LARGE_BLOCK_SIZE;
  G_MOVIE_STREAM_BUFFER_COUNT = MOVIE_STREAM_DEFAULT_BUFFER_COUNT;
}

void
configure_wide_movie_stream_buffers(void)
{
  G_MOVIE_STREAM_BLOCK_SIZE   = MOVIE_STREAM_LARGE_BLOCK_SIZE;
  G_MOVIE_STREAM_BUFFER_COUNT = MOVIE_STREAM_WIDE_BUFFER_COUNT;
}

void
configure_compact_movie_stream_buffers(void)
{
  G_MOVIE_STREAM_BLOCK_SIZE   = MOVIE_STREAM_COMPACT_BLOCK_SIZE;
  G_MOVIE_STREAM_BUFFER_COUNT = MOVIE_STREAM_DEFAULT_BUFFER_COUNT;
}
