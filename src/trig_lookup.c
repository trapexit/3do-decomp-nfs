int32
sine_1024(int32 angle_)
{
  uint32 angle_bits;
  uint32 index;
  int32  value;

  angle_bits = (uint32) angle_;
  index      = (angle_bits & TRIG_INDEX_MASK);
  if((angle_bits & TRIG_REFLECT_BIT) != 0)
    {
      index = (TRIG_QUARTER_STEPS - index);
    }

  value = G_SINE_QUARTER_WAVE[index];
  if((angle_bits & TRIG_NEGATE_BIT) != 0)
    {
      value = -value;
    }

  return value;
}

int32
cosine_1024(int32 angle_)
{
  return sine_1024((int32) ((uint32) angle_ + TRIG_COSINE_OFFSET));
}

void
calculate_sine_cosine_1024(int32 angle_, int32 *sine_, int32 *cosine_)
{
  uint32 angle_bits;
  uint32 index;
  int32  value;

  angle_bits = (uint32) angle_;
  index      = (angle_bits & TRIG_INDEX_MASK);
  if((angle_bits & TRIG_REFLECT_BIT) != 0)
    index = (TRIG_QUARTER_STEPS - index);
  value = G_SINE_QUARTER_WAVE[index];
  if((angle_bits & TRIG_NEGATE_BIT) != 0)
    value = -value;
  *sine_ = value;

  angle_bits += TRIG_COSINE_OFFSET;
  index = (angle_bits & TRIG_INDEX_MASK);
  if((angle_bits & TRIG_REFLECT_BIT) != 0)
    index = (TRIG_QUARTER_STEPS - index);
  value = G_SINE_QUARTER_WAVE[index];
  if((angle_bits & TRIG_NEGATE_BIT) != 0)
    value = -value;
  *cosine_ = value;
}

int32
calculate_signed_arcsine_ratio(int32 numerator_, int32 denominator_)
{
  uint32 magnitude;
  uint32 ratio;
  int32  angle;
  int32  negate;

  magnitude = (uint32) numerator_;
  negate    = 0;
  if(numerator_ < 0)
    {
      magnitude = (0U - magnitude);
      negate    = 1;
    }

  if(magnitude >= (uint32) denominator_)
    {
      angle = ARCSINE_QUARTER_TURN;
    }
  else
    {
      ratio = ((magnitude << ARCSINE_RATIO_FIXED_SHIFT) / (uint32) denominator_);
      angle = g_ARCSINE_RATIO_TABLE[ratio >> ARCSINE_RATIO_INDEX_SHIFT];
    }

  if(negate != 0)
    angle = -angle;

  return angle;
}
