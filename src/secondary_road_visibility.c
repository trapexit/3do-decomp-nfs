/* Tests secondary-road cel quads against the active screen bounds. */

#include "frontend_transition.h"
#include "road_render.h"

#define SECONDARY_ROAD_QUAD_RENDER_TYPE_LIMIT 5
#define SECONDARY_ROAD_SCREEN_TOP 0
#define SECONDARY_ROAD_QUAD_FIRST_INDEX 0
#define SECONDARY_ROAD_QUAD_SECOND_INDEX 1
#define SECONDARY_ROAD_QUAD_THIRD_INDEX 2
#define SECONDARY_ROAD_QUAD_FOURTH_INDEX 3

int32
is_secondary_road_quad_visible(Point2 *quad_, int32 render_type_)
{
  if(render_type_ < SECONDARY_ROAD_QUAD_RENDER_TYPE_LIMIT)
    {
      if((quad_[SECONDARY_ROAD_QUAD_FIRST_INDEX].x > g_FRONTEND_MENU_COORDINATES.x) &&
         (quad_[SECONDARY_ROAD_QUAD_SECOND_INDEX].x > g_FRONTEND_MENU_COORDINATES.x) &&
         (quad_[SECONDARY_ROAD_QUAD_THIRD_INDEX].x > g_FRONTEND_MENU_COORDINATES.x) &&
         (quad_[SECONDARY_ROAD_QUAD_FOURTH_INDEX].x > g_FRONTEND_MENU_COORDINATES.x))
        return 0;
      if((quad_[SECONDARY_ROAD_QUAD_FIRST_INDEX].x < SECONDARY_ROAD_SCREEN_TOP) &&
         (quad_[SECONDARY_ROAD_QUAD_SECOND_INDEX].x < SECONDARY_ROAD_SCREEN_TOP) &&
         (quad_[SECONDARY_ROAD_QUAD_THIRD_INDEX].x < SECONDARY_ROAD_SCREEN_TOP) &&
         (quad_[SECONDARY_ROAD_QUAD_FOURTH_INDEX].x < SECONDARY_ROAD_SCREEN_TOP))
        return 0;
    }
  else
    {
      if((quad_[SECONDARY_ROAD_QUAD_FIRST_INDEX].x < SECONDARY_ROAD_SCREEN_TOP) &&
         (quad_[SECONDARY_ROAD_QUAD_SECOND_INDEX].x < SECONDARY_ROAD_SCREEN_TOP) &&
         (quad_[SECONDARY_ROAD_QUAD_THIRD_INDEX].x < SECONDARY_ROAD_SCREEN_TOP) &&
         (quad_[SECONDARY_ROAD_QUAD_FOURTH_INDEX].x < SECONDARY_ROAD_SCREEN_TOP))
        return 0;
      if((quad_[SECONDARY_ROAD_QUAD_FIRST_INDEX].x > g_FRONTEND_MENU_COORDINATES.x) &&
         (quad_[SECONDARY_ROAD_QUAD_SECOND_INDEX].x > g_FRONTEND_MENU_COORDINATES.x) &&
         (quad_[SECONDARY_ROAD_QUAD_THIRD_INDEX].x > g_FRONTEND_MENU_COORDINATES.x) &&
         (quad_[SECONDARY_ROAD_QUAD_FOURTH_INDEX].x > g_FRONTEND_MENU_COORDINATES.x))
        return 0;
    }

  if((quad_[SECONDARY_ROAD_QUAD_FIRST_INDEX].y > g_FRONTEND_MENU_COORDINATES.y) &&
     (quad_[SECONDARY_ROAD_QUAD_FOURTH_INDEX].y > g_FRONTEND_MENU_COORDINATES.y))
    return 0;
  return 1;
}
