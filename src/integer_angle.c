int32
calculate_integer_angle(int32 x_, int32 y_)
{
  uint32 x_magnitude;
  uint32 y_magnitude;
  uint32 temporary;
  uint32 scaled_numerator;
  uint32 quotient;
  uint32 quotient_bit;
  uint32 flags;
  int32  shift;
  int32  angle;

  flags       = 0;
  y_magnitude = (uint32) y_;
  if(y_ < 0)
    {
      y_magnitude = 0U - y_magnitude;
      flags |= ANGLE_FLAG_Y_NEGATIVE;
    }
  x_magnitude = (uint32) x_;
  if(x_ < 0)
    {
      x_magnitude = 0U - x_magnitude;
      flags |= ANGLE_FLAG_X_NEGATIVE;
    }

  if(y_magnitude == x_magnitude)
    {
      angle = ANGLE_OCTANT;
    }
  else
    {
      if((int32) y_magnitude < (int32) x_magnitude)
        {
          temporary   = x_magnitude;
          x_magnitude = y_magnitude;
          y_magnitude = temporary;
          flags |= ANGLE_FLAG_SWAPPED;
        }

      scaled_numerator = (x_magnitude << ANGLE_RATIO_SHIFT);
      quotient         = 0;
      shift            = ANGLE_DIVIDE_TOP_SHIFT;
      while(shift >= 0)
        {
          quotient_bit = 0;
          if((scaled_numerator >> shift) >= y_magnitude)
            {
              scaled_numerator -= (y_magnitude << shift);
              quotient_bit = 1;
            }
          quotient = ((quotient << 1) | quotient_bit);
          shift--;
        }
      angle = G_ANGLE_RATIO_TABLE[quotient];
    }

  switch(flags)
    {
      case 0:
        return angle;
      case ANGLE_FLAG_SWAPPED:
        return ANGLE_QUARTER_TURN - angle;
      case ANGLE_FLAG_Y_NEGATIVE:
        return ANGLE_HALF_TURN - angle;
      case ANGLE_FLAG_Y_NEGATIVE | ANGLE_FLAG_SWAPPED:
        return ANGLE_QUARTER_TURN + angle;
      case ANGLE_FLAG_X_NEGATIVE:
        return -angle;
      case ANGLE_FLAG_X_NEGATIVE | ANGLE_FLAG_SWAPPED:
        return angle - ANGLE_QUARTER_TURN;
      case ANGLE_FLAG_X_NEGATIVE | ANGLE_FLAG_Y_NEGATIVE:
        return angle - ANGLE_HALF_TURN;
      default:
        return -(ANGLE_QUARTER_TURN + angle);
    }
}
