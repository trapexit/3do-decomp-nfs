int
tolower(int character_)
{
  if((__ctype[character_] & RUNTIME_CTYPE_UPPERCASE) != 0)
    return (character_ + RUNTIME_CTYPE_ASCII_CASE_OFFSET);

  return character_;
}

int
toupper(int character_)
{
  if(((__ctype[character_] & RUNTIME_CTYPE_LOWERCASE) != 0) &&
     (character_ != RUNTIME_CTYPE_LATIN_SMALL_SHARP_S))
    return (character_ - RUNTIME_CTYPE_ASCII_CASE_OFFSET);

  return character_;
}
