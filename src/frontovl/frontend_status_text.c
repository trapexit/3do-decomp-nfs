#include "frontend_status_text.h"

#include "runtime_memory.h"

#define FRONTEND_STATUS_TEXT_X 47
#define FRONTEND_STATUS_FIRST_Y 74
#define FRONTEND_STATUS_SECOND_Y 150
#define FRONTEND_STATUS_THIRD_Y 191

char g_FRONTEND_STATUS_FIRST_TEXT[FRONTEND_STATUS_TEXT_CAPACITY];
char g_FRONTEND_STATUS_THIRD_TEXT[FRONTEND_STATUS_TEXT_CAPACITY];
char g_FRONTEND_STATUS_SECOND_TEXT[FRONTEND_STATUS_TEXT_CAPACITY];
char g_FRONTEND_OVERLAY_STATUS_TEXT[FRONTEND_STATUS_TEXT_CAPACITY];

void
draw_frontend_status_text(void)
{
  draw_runtime_text(g_FRONTEND_STATUS_FIRST_TEXT, FRONTEND_STATUS_TEXT_X, FRONTEND_STATUS_FIRST_Y);
  draw_runtime_text(g_FRONTEND_STATUS_SECOND_TEXT,
                    FRONTEND_STATUS_TEXT_X,
                    FRONTEND_STATUS_SECOND_Y);
  draw_runtime_text(g_FRONTEND_STATUS_THIRD_TEXT, FRONTEND_STATUS_TEXT_X, FRONTEND_STATUS_THIRD_Y);
}
